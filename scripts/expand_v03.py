(ROOT/'docs/advanced-candidates.json').write_text(json.dumps([r for r in R if r['name'] in deferred],ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
R=[r for r in R if r['name'] not in deferred]
# Regional labels are editorial browsing aids, not exclusive historical origins.
mapping={
'川菜':['鱼香肉丝','宫保鸡丁','麻婆豆腐','鱼香茄子','蚂蚁上树','蒜苗回锅肉'],
'鲁菜':['锅塌豆腐'],
'粤菜':['蒜蓉粉丝蒸虾','豆豉蒸小排','香菇蒸滑鸡','上汤娃娃菜','清蒸鲈鱼'],
'津菜':['天津独面筋'],
'东北风味':['少油版地三鲜','白菜猪肉炖粉条','松仁玉米']}
for r in R:
    if not r.get('cuisine'):
        r['cuisine']=next((c for c,names in mapping.items() if r['name'] in names),'早餐' if r['category']=='早餐' else '家常风味')
    r.setdefault('cuisineNote','家庭改编；菜系用于风味浏览，不代表唯一产地。')
    r['editorial']=r['editorial'].replace('新增配方','配方')
    if r.get('edition')=='0.3.0':
        names=' '.join(i['name'] for i in r['ingredients'])
        r['allergens']=[label for label,terms in [('蛋',['鸡蛋','蛋饺','鹌鹑蛋']),('奶',['牛奶','黄油']),('大豆',['豆腐','豆瓣','豆豉','生抽','老抽']),('小麦',['面粉','生抽','豆瓣酱']),('甲壳类',['虾']),('贝类',['蚝油','海蛎'])] if any(x in names for x in terms)]
        r['review']={'editorial':'detailed-draft','kitchen':'not-tested','device':'pending'}
    r.setdefault('review',{'editorial':'needs-detail-review','kitchen':'not-tested','device':'pending'})
    if r['name'] in ['红烧肉','香蕉厚蛋烧']:r['review']['editorial']='detailed-draft'
    # Difficulty is about technique, not cuisine identity or duration alone.
    easy_groups={'粥羹碗餐','蔬菜小炒','白灼','薯芋杂粮'}
    challenging={'宫保鸡丁','锅塌豆腐','清炖狮子头','水煮肉片','小炒黄牛肉','荔枝肉（香煎版）','香菇糯米烧卖','白菜鸡肉蒸饺','鲜虾鸡蛋肠粉','红枣玉米面发糕','香菇豆腐小蒸包','香蕉厚蛋烧','金钱蛋'}
    easy_names={'西红柿炒鸡蛋','韭菜炒鸡蛋','黄瓜炒鸡蛋','洋葱炒鸡蛋','可乐鸡翅','红烧肉','清蒸鲈鱼','海苔肉松饭团','豆乳燕麦水果碗','白灼菜心'}
    level=3 if r['name'] in challenging else 1 if r['group'] in easy_groups or r['name'] in easy_names else 2
    r['difficulty']=level
    r['difficultyReason']={1:'操作较少，以基础切配和状态检查为主；耗时仍需单独查看。',2:'需要分次下料、翻面或控制汁量，先备齐材料会更从容。',3:'需要成形、上浆、快速炒制或多道工序，建议先看完整做法。'}[level]
assert len(R)==174
assert len(set(r['id'] for r in R))==len(R)
assert len(set(r['name'] for r in R))==len(R)
(ROOT/'web/recipes.json').write_text(json.dumps(R,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
(ROOT/'web/recipes.js').write_text('window.RECIPES = '+json.dumps(R,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
from collections import Counter
report={'total':len(R),'cuisines':dict(Counter(r['cuisine'] for r in R)),'stepCounts':dict(Counter(len(r['steps']) for r in R)),'detailedDrafts':[r['name'] for r in R if r['review']['editorial']=='detailed-draft'],'kitchenTested':0,'sources':[s for r in R if r.get('edition')=='0.3.0' for s in r['sources']]}
(ROOT/'docs/v03-content-audit.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'total':len(R),'cuisines':report['cuisines']},ensure_ascii=False))
