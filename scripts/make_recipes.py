recipes = []
def ing(spec):
    out=[]
    for part in spec.split(';'):
        name,qty,unit=part.split('|')
        out.append(dict(name=name,amount=float(qty),unit=unit))
    return out
def step(title,heat,seconds,text,check):
    return dict(title=title,heat=heat,seconds=seconds,text=text,check=check)
def add(name,cat,minutes,emoji,spec,steps,tip,source=None,spicy=False,prep=0):
    ingredients=ing(spec)
    for key,unit in [('盐','g'),('食用油','ml')]:
        if not any(i['name']==key for i in ingredients): ingredients.append(dict(name=key,amount=0,unit=unit))
    refs=[]
    for n in (source or [name]):
        files=list((UP/'dishes').rglob(n+'.md'))
        if files:
            f=files[0]; path=f.relative_to(UP).as_posix()
            refs.append(dict(title='HowToCook · '+n,url='https://github.com/Anduin2017/HowToCook/blob/'+COMMIT+'/'+path,kind='recipe' if n==name else 'technique',path=path,sha256=hashlib.sha256(f.read_bytes()).hexdigest()))
    if not refs: raise ValueError('Missing source: '+name)
    recipes.append(dict(id=('d' if cat=='家常菜' else 'b')+str(sum(r['category']==cat for r in recipes)+1).zfill(2),name=name,category=cat,minutes=minutes,prepMinutes=prep,servings=2,emoji=emoji,spicy=spicy,ingredients=ingredients,steps=steps,tips=[tip],sources=refs,videos=[],editorial='家庭量化改编；份量和计时为参考，未逐道试做。以本页熟透判断为准。'))

